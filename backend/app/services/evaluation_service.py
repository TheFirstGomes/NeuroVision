"""
RAG Evaluation Service — LLM-as-judge.

Scores each RAG answer on two dimensions:
  - Faithfulness (1–5): grounded in the retrieved chunks?
  - Relevancy   (1–5): actually answers the question?

Composite score = 0.6 × faithfulness + 0.4 × relevancy
(faithfulness weighted higher — factual grounding is the critical failure mode)

Runs as a FastAPI BackgroundTask so it never blocks the user response.
Scores are stored in SQLite for trending and diagnosis.
"""
import json
import re
from typing import Optional

import structlog
from groq import Groq

from app.infrastructure import database as db

logger = structlog.get_logger(__name__)

_EVAL_PROMPT = """\
You are evaluating an educational question-answer system about neuro-ophthalmology.

Question asked: {question}

Retrieved source chunks used as context:
{chunks_text}

Answer given to the student: {answer}

Rate the answer on two dimensions using integers from 1 to 5:

  faithfulness — Is the answer factually grounded in the retrieved chunks above?
                 1 = contradicts or ignores the chunks  |  5 = fully grounded in the chunks
  relevancy    — Does the answer actually address what was asked?
                 1 = off-topic or evasive               |  5 = directly and completely answers

Respond with ONLY valid JSON, no extra text:
{{"faithfulness": <int>, "relevancy": <int>}}"""


class EvaluationService:
    """
    Asynchronous LLM-as-judge for RAG quality monitoring.
    Uses the same Groq API key already configured in the application.
    """

    def __init__(self, groq_api_key: str, model: str = "llama-3.3-70b-versatile") -> None:
        self._client = Groq(api_key=groq_api_key)
        self._model = model

    def evaluate(
        self,
        session_id: str,
        question: str,
        answer: str,
        chunks: list[dict],
    ) -> None:
        """
        Score one QA pair using the actual retrieved chunks as ground truth.
        Designed to be called as a BackgroundTask — never raises.

        Args:
            session_id: For correlation with traces and messages.
            question:   The user's original question.
            answer:     The answer generated by the RAG pipeline.
            chunks:     The retrieved chunks (with source, similarity_score, content_snippet).
        """
        faithfulness: Optional[int] = None
        relevancy: Optional[int] = None
        composite: Optional[float] = None

        try:
            # Build chunk summary for the evaluator prompt
            if chunks:
                chunks_text = "\n\n".join(
                    f"[Chunk {i+1} | source: {c.get('source', '?')} | "
                    f"similarity: {c.get('similarity_score', '?')}]\n{c.get('content_snippet', '')}"
                    for i, c in enumerate(chunks)
                )
            else:
                chunks_text = "(no chunks retrieved)"

            prompt = _EVAL_PROMPT.format(
                question=question,
                chunks_text=chunks_text,
                answer=answer[:1200],
            )

            completion = self._client.chat.completions.create(
                model=self._model,
                messages=[{"role": "user", "content": prompt}],
                temperature=0.0,
                max_tokens=64,
            )

            raw = completion.choices[0].message.content or ""

            match = re.search(r"\{[^}]+\}", raw)
            if match:
                scores = json.loads(match.group())
                f = int(scores.get("faithfulness", 0))
                r = int(scores.get("relevancy", 0))
                faithfulness = f if 1 <= f <= 5 else None
                relevancy    = r if 1 <= r <= 5 else None

            if faithfulness is not None and relevancy is not None:
                composite = round(0.6 * faithfulness + 0.4 * relevancy, 2)

            logger.info(
                "evaluation.scored",
                session_id=session_id,
                faithfulness=faithfulness,
                relevancy=relevancy,
                composite=composite,
                avg_chunk_similarity=round(
                    sum(c.get("similarity_score", 0) for c in chunks) / len(chunks), 3
                ) if chunks else None,
            )

        except Exception as exc:
            logger.warning("evaluation.failed", session_id=session_id, error=str(exc))

        finally:
            db.add_evaluation(
                session_id=session_id,
                question=question,
                answer=answer,
                faithfulness_score=faithfulness,
                relevancy_score=relevancy,
                composite_score=composite,
            )
